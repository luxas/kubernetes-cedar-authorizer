#!/usr/bin/env bash
# Build and audit everything; write docs/status.md. Exit non-zero on any failure.
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
export PATH="$HOME/.elan/bin:$PATH"
cd "$ROOT"
fail=0
LOG="$(mktemp -d "${KIROCREW_SCRATCH:-${TMPDIR:-/tmp}}/check.XXXXXX")"

echo "== lake build"
( cd lean && lake build ) >"$LOG/lake.log" 2>&1; lake_rc=$?
tail -1 "$LOG/lake.log"; [ $lake_rc -eq 0 ] || fail=1

echo "== cargo test --workspace"
cargo test --workspace >"$LOG/cargo.log" 2>&1; cargo_rc=$?
[ $cargo_rc -eq 0 ] || { fail=1; tail -30 "$LOG/cargo.log"; }
rust_pass=$(grep -E '^test result' "$LOG/cargo.log" | sed -E 's/.* ([0-9]+) passed.*/\1/' | awk '{s+=$1} END {print s+0}')
rust_ign=$(grep -E '^test result' "$LOG/cargo.log" | sed -E 's/.* ([0-9]+) ignored.*/\1/' | awk '{s+=$1} END {print s+0}')
rust_fail=$(grep -E '^test result' "$LOG/cargo.log" | sed -E 's/.* ([0-9]+) failed.*/\1/' | awk '{s+=$1} END {print s+0}')
[ "${rust_pass:-0}" -gt 0 ] || { echo "VACUOUS: 0 Rust tests ran"; fail=1; }

echo "== sorry check (outside comments)"
sorry_out=$(python3 - <<'PY'
import re, sys, pathlib
hits = []
for root in ("lean/K8sAuthz", "lean/CedarK8s", "lean/mirror"):
    for p in pathlib.Path(root).rglob("*.lean"):
        s = p.read_text()
        # strip (nested) block comments, then line comments and string literals
        out, depth, i = [], 0, 0
        while i < len(s):
            if s.startswith("/-", i): depth += 1; i += 2
            elif s.startswith("-/", i) and depth: depth -= 1; i += 2
            else:
                if depth == 0: out.append(s[i])
                i += 1
        text = "".join(out)
        for n, line in enumerate(text.split("\n"), 1):
            line = re.sub(r'"(\\.|[^"\\])*"', '""', line.split("--")[0])
            if re.search(r"\bsorry\b", line): hits.append(f"{p}:{n}")
print("\n".join(hits))
PY
)
if [ -n "$sorry_out" ]; then echo "sorry found:"; echo "$sorry_out"; fail=1; sorry_n=$(echo "$sorry_out" | wc -l); else sorry_n=0; fi
echo "sorry: $sorry_n"

echo "== axioms"
( cd lean && lake env lean scripts/Axioms.lean ) >"$LOG/axioms.log" 2>&1 || { fail=1; cat "$LOG/axioms.log"; }
grep -q "reauthorize_is_sound' depends on axioms: \[propext, Classical.choice, Quot.sound\]" "$LOG/axioms.log" \
  || { echo "reauthorize_is_sound axioms unexpected"; fail=1; }
grep -c "depends on axioms" "$LOG/axioms.log" | sed 's/^/axiom reports: /'
if grep -E "^'K8sAuthz\." "$LOG/axioms.log" | grep -q sorryAx; then echo "sorryAx in a K8sAuthz headline theorem"; fail=1; fi
k8s_ax=$(grep -cE "^'K8sAuthz\." "$LOG/axioms.log")
k8s_nonstd=$(grep -E "^'K8sAuthz\." "$LOG/axioms.log" | grep "depends on axioms" | sed 's/.*axioms: //' | tr -d '[],' | tr ' ' '\n' | grep -vxE 'propext|Classical.choice|Quot.sound|' | wc -l)
[ "$k8s_nonstd" -eq 0 ] || { echo "K8sAuthz theorem with non-standard axioms"; fail=1; }

echo "== Cedar import isolation"
leaks=$(grep -rlE '^import +Cedar\.(TPE|Thm\.TPE)' lean --include='*.lean' --exclude-dir=.lake | grep -v -e '^lean/CedarK8s/Adapter.lean$' -e '^lean/scripts/Axioms.lean$' || true)
[ -z "$leaks" ] || { echo "Cedar.TPE imported outside Adapter.lean: $leaks"; fail=1; }
cleaks=$(grep -rlE 'cedar_policy' crates/core --include='*.rs' | grep -v '^crates/core/src/cedar_adapter.rs$' || true)
[ -z "$cleaks" ] || { echo "cedar_policy named outside cedar_adapter.rs: $cleaks"; fail=1; }

mods=$(find lean/mirror -name '*.lean' | wc -l)
thms=$(grep -rhE '^theorem ' lean/mirror --include='*.lean' | wc -l)
thms_all=$(grep -rhE '^(@\[[^]]*\] )?(private |protected )?(theorem|lemma) ' lean/mirror lean/K8sAuthz lean/CedarK8s --include='*.lean' | wc -l)
axs=$(grep -rhE '^axiom ' lean/mirror --include='*.lean' | wc -l)
own_mods=$(find lean/K8sAuthz lean/CedarK8s -name '*.lean' | wc -l)
k8s_thms=$(grep -rhE '^(@\[[^]]*\] )?(private |protected )?(theorem|lemma) ' lean/K8sAuthz --include='*.lean' | wc -l)
k8s_ex=$(grep -rhE '^example' lean/K8sAuthz --include='*.lean' | wc -l)
if [ $fail -eq 0 ]; then verdict=PASS; else verdict=FAIL; fi

cat > docs/status.md <<EOT
# Status (generated by scripts/check.sh; do not edit)

Verdict: **$verdict**

| Item | Value |
|---|---|
| Lean toolchain | $(cat lean/lean-toolchain) |
| cedar-spec pin | $(grep -m1 'rev =' lean/lakefile.toml | cut -d'"' -f2) |
| \`lake build\` | $([ $lake_rc -eq 0 ] && echo ok || echo FAILED) |
| Mirror modules (\`lean/mirror\`) | $mods (STATUS.md claims 23, see lean/mirror/ADAPTATIONS.md) |
| Mirror theorems (\`^theorem \`) | $thms (STATUS.md: 347) |
| Theorems incl. \`@[..]\`/private, mirror + K8sAuthz + CedarK8s | $thms_all |
| Mirror axiom declarations | $axs (STATUS.md: 2) |
| Own Lean modules (K8sAuthz, CedarK8s) | $own_mods |
| K8sAuthz theorems / examples | $k8s_thms / $k8s_ex |
| K8sAuthz headline theorems audited (standard axioms only) | $k8s_ax |
| \`sorry\` outside comments | $sorry_n |
| Rust tests passed / ignored / failed | ${rust_pass:-0} / ${rust_ign:-0} / ${rust_fail:-0} |

## Axiom audit

\`\`\`
$(cat "$LOG/axioms.log")
\`\`\`
EOT
echo "== summary ($verdict)"; cat docs/status.md
exit $fail
